-- ==========================================================
-- BASE DE DONNEES "chahia" - GPAO Elevage (Pondeuse)
-- FICHIER UNIQUE D'INSTALLATION COMPLETE : à importer dans
-- phpMyAdmin / MySQL (utf8mb4). Contient TOUT en un seul import :
--   - le schéma complet (v3, utilisateur = ouvrier)
--   - les alertes automatiques (mortalité, ponte, absence de saisie)
--   - les factures multi-blocs administrateur
--   - les données de démonstration + le jeu de données étendu pour
--     les statistiques (2025 vs 2026, ~1090 saisies)
-- Il n'y a plus rien d'autre à importer après celui-ci.
--
-- v2 : suppression de la hiérarchie Région > Société > Centre.
--      Un BLOC contient directement un ou plusieurs BATIMENTS.
-- v3 : l'utilisateur EST l'ouvrier (fusion des tables). Chaque
--      utilisateur (ouvrier) non-admin voit/contrôle UN SEUL bloc.
-- ==========================================================

CREATE DATABASE IF NOT EXISTS chahia CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE chahia;

-- ----------------------------------------------------------
-- Réinstallation propre : on supprime les anciennes tables
-- (y compris celles de l'ancienne hiérarchie Région>Société>Centre
-- et de l'ancien système ouvriers séparé, si elles existent encore)
-- avant de recréer le nouveau schéma.
-- ----------------------------------------------------------
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS alertes;
DROP TABLE IF EXISTS parametres_alertes;
DROP TABLE IF EXISTS factures;
DROP TABLE IF EXISTS prix_oeuf;
DROP TABLE IF EXISTS affectations_ouvriers;
DROP TABLE IF EXISTS ouvriers;
DROP TABLE IF EXISTS utilisateurs;
DROP TABLE IF EXISTS saisie_valeurs;
DROP TABLE IF EXISTS parametres_suivi;
DROP TABLE IF EXISTS saisies;
DROP TABLE IF EXISTS batiments;
DROP TABLE IF EXISTS blocs;
DROP TABLE IF EXISTS centres;
DROP TABLE IF EXISTS societes;
DROP TABLE IF EXISTS regions;
SET FOREIGN_KEY_CHECKS = 1;

-- ----------------------------------------------------------
-- 1) Blocs (lots) — un bloc = un lot, qui contient >= 1 bâtiment
-- ----------------------------------------------------------
CREATE TABLE blocs (
    id                     INT AUTO_INCREMENT PRIMARY KEY,
    exercice               INT NOT NULL,
    speculation            VARCHAR(30) DEFAULT 'Pondeuse',
    nom                    VARCHAR(100) NOT NULL,
    lot_code               VARCHAR(30)  NOT NULL,
    superficie             INT DEFAULT 0,
    effectif_entree        INT DEFAULT 0,
    date_debut_nettoyage   DATE NULL,
    date_entree_effectif   DATE NULL,
    date_cloture           DATE NULL,
    etat                   VARCHAR(20) DEFAULT 'EN COURS',
    valide                 TINYINT(1) DEFAULT 0,
    UNIQUE KEY uk_lot_code (lot_code)
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 2) Bâtiments — chaque bâtiment appartient directement à un bloc
-- ----------------------------------------------------------
CREATE TABLE batiments (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    nom              VARCHAR(100) NOT NULL,
    bloc_id          INT NOT NULL,
    age_semaines     INT DEFAULT 0,
    souche           VARCHAR(50)  DEFAULT 'LOHMANN',
    effectif_depart  INT DEFAULT 0,
    FOREIGN KEY (bloc_id) REFERENCES blocs(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 3) Saisies journalières (TDB Pondeuse) + détail de tri
-- ----------------------------------------------------------
CREATE TABLE saisies (
    id                        INT AUTO_INCREMENT PRIMARY KEY,
    batiment_id               INT NOT NULL,
    date_saisie                DATE NOT NULL,
    effectif_present           INT DEFAULT 0,
    taux_ponte_objectif        DECIMAL(6,2) DEFAULT 0,
    production_totale          INT DEFAULT 0,
    consommation_eau           DECIMAL(10,2) DEFAULT 0,
    consommation_aliment       DECIMAL(10,2) DEFAULT 0,
    consommation_electricite   DECIMAL(10,2) DEFAULT 0,
    mortalite                  INT DEFAULT 0,
    reforme_tri                 INT DEFAULT 0,
    pc_pct                     DECIMAL(6,2) DEFAULT 0,
    sale_pct                   DECIMAL(6,2) DEFAULT 0,
    casse_vendue_pct           DECIMAL(6,2) DEFAULT 0,
    casse_non_vendue_pct       DECIMAL(6,2) DEFAULT 0,
    temp_min                   DECIMAL(5,2) NULL,
    temp_max                   DECIMAL(5,2) NULL,
    humidite                   DECIMAL(5,2) NULL,
    nombre_ouvriers            INT DEFAULT 0,
    poids_moyen_oeuf           DECIMAL(6,2) NULL,
    consommation_alveole       INT DEFAULT 0,
    remarque                   VARCHAR(255) NULL,
    UNIQUE KEY uk_batiment_date (batiment_id, date_saisie),
    FOREIGN KEY (batiment_id) REFERENCES batiments(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Détail du tri des oeufs par rubrique (codes OBV/ODJ/OJOV/OS... vus dans le logiciel GPAO)
CREATE TABLE parametres_suivi (
    code        VARCHAR(20) PRIMARY KEY,
    libelle_fr  VARCHAR(150) NOT NULL,
    libelle_ar  VARCHAR(150) NULL
) ENGINE=InnoDB;

CREATE TABLE saisie_valeurs (
    id         INT AUTO_INCREMENT PRIMARY KEY,
    saisie_id  INT NOT NULL,
    code       VARCHAR(20) NOT NULL,
    valeur     DECIMAL(12,2) DEFAULT 0,
    UNIQUE KEY uk_saisie_code (saisie_id, code),
    FOREIGN KEY (saisie_id) REFERENCES saisies(id) ON DELETE CASCADE,
    FOREIGN KEY (code) REFERENCES parametres_suivi(code) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 4) Utilisateurs = Ouvriers. Un compte utilisateur EST un ouvrier.
--    Chaque ouvrier (non-admin) peut voir/contrôler EXACTEMENT UN
--    SEUL bloc (bloc_id). L'admin n'est rattaché à aucun bloc et
--    voit/contrôle tout.
-- ----------------------------------------------------------
CREATE TABLE utilisateurs (
    id                  INT AUTO_INCREMENT PRIMARY KEY,
    nom_utilisateur     VARCHAR(50) NOT NULL,
    mot_de_passe_hash   VARCHAR(255) NOT NULL,
    nom_complet         VARCHAR(100) NOT NULL,
    telephone           VARCHAR(30) NULL,
    email               VARCHAR(150) NULL,
    fonction            VARCHAR(60) NULL DEFAULT 'Ouvrier responsable de bloc',
    role                ENUM('admin','utilisateur') NOT NULL DEFAULT 'utilisateur',
    bloc_id             INT NULL,
    actif               TINYINT(1) NOT NULL DEFAULT 1,
    UNIQUE KEY uk_nom_utilisateur (nom_utilisateur),
    UNIQUE KEY uk_bloc_id (bloc_id),
    FOREIGN KEY (bloc_id) REFERENCES blocs(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 5) Prix de l'oeuf (fixé chaque jour par l'administrateur)
-- ----------------------------------------------------------
CREATE TABLE prix_oeuf (
    id             INT AUTO_INCREMENT PRIMARY KEY,
    date_prix      DATE NOT NULL,
    prix_unitaire  DECIMAL(10,3) NOT NULL,
    defini_par     INT NULL,
    UNIQUE KEY uk_date_prix (date_prix),
    FOREIGN KEY (defini_par) REFERENCES utilisateurs(id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 6) Factures (commandes) - un utilisateur commande une quantité
--    d'oeufs pour son bloc, au prix du jour, limitée par le stock
-- ----------------------------------------------------------
CREATE TABLE factures (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    numero_facture   VARCHAR(30) NOT NULL,
    date_facture     DATE NOT NULL,
    utilisateur_id   INT NOT NULL,
    bloc_id          INT NOT NULL,
    quantite         INT NOT NULL,
    prix_unitaire    DECIMAL(10,3) NOT NULL,
    montant_total    DECIMAL(14,3) AS (quantite * prix_unitaire) STORED,
    statut           ENUM('en_attente','validee','annulee') NOT NULL DEFAULT 'en_attente',
    KEY idx_numero_facture (numero_facture),
    FOREIGN KEY (utilisateur_id) REFERENCES utilisateurs(id) ON DELETE CASCADE,
    FOREIGN KEY (bloc_id) REFERENCES blocs(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ----------------------------------------------------------
-- 7) Alertes automatiques
--    - parametres_alertes : seuils configurables par l'admin (page
--      Paramétrage), une seule ligne (id=1).
--    - alertes : historique des alertes déclenchées. Volontairement,
--      AUCUNE requête DELETE n'existe nulle part dans l'application
--      pour cette table : l'historique des alertes ne peut pas être
--      effacé, ni par l'admin ni par l'utilisateur.
-- ----------------------------------------------------------
CREATE TABLE parametres_alertes (
    id                       INT PRIMARY KEY DEFAULT 1,
    seuil_mortalite_pct      DECIMAL(6,2) NOT NULL DEFAULT 2.00,
    seuil_baisse_ponte_pct   DECIMAL(6,2) NOT NULL DEFAULT 10.00,
    jours_sans_saisie        INT NOT NULL DEFAULT 2,
    email_actif              TINYINT(1) NOT NULL DEFAULT 0
) ENGINE=InnoDB;
INSERT INTO parametres_alertes (id, seuil_mortalite_pct, seuil_baisse_ponte_pct, jours_sans_saisie, email_actif)
VALUES (1, 2.00, 10.00, 2, 0);

CREATE TABLE alertes (
    id               INT AUTO_INCREMENT PRIMARY KEY,
    type_alerte      ENUM('mortalite','ponte','absence_saisie') NOT NULL,
    bloc_id          INT NOT NULL,
    batiment_id      INT NULL,
    date_alerte      DATE NOT NULL,
    valeur_mesuree   DECIMAL(10,2) NULL,
    seuil_applique   DECIMAL(10,2) NULL,
    message          TEXT NOT NULL,
    date_creation    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uk_alerte (type_alerte, batiment_id, date_alerte),
    FOREIGN KEY (bloc_id) REFERENCES blocs(id) ON DELETE CASCADE,
    FOREIGN KEY (batiment_id) REFERENCES batiments(id) ON DELETE CASCADE
) ENGINE=InnoDB;

